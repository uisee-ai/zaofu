import { expect, test } from "@playwright/test";
import { installUiFixture } from "./ui-alignment.fixture";

test.use({ viewport: { width: 1440, height: 1000 }, locale: "en-US" });
test.describe.configure({ timeout: 60_000 });

test("sidebar preserves menu order, navigates as icons, and remembers collapse", async ({ page }, info) => {
  const { writes, errors } = await installUiFixture(page);
  await page.goto("/?project=ui-review&page=board");
  await expect(page.locator(".task-card")).toHaveCount(6);
  const rail = page.getByRole("region", { name: "Navigation rail" });
  const menu = ["Overview", "Inbox", "Tasks", "Workflows", "Agents", "Automations", "Delivery", "Loop", "Traces", "Open Channels", "New Channel", "Settings"];
  expect(await rail.locator(".rail-nav-button").evaluateAll((nodes) => nodes.map((node) => node.getAttribute("aria-label")))).toEqual(menu);
  expect((await rail.boundingBox())?.width).toBe(252);
  await expect(rail.getByLabel("Project", { exact: true })).toBeVisible();
  await expect(rail.getByRole("heading", { name: "ZaoFu", exact: true })).toHaveCSS("font-size", "13.5px");
  expect((await rail.locator(".rail-brand-mark").boundingBox())?.width).toBe(22);
  await page.screenshot({ path: info.outputPath("sidebar-expanded.png") });
  await rail.locator("summary").click();
  await expect(rail.getByRole("button", { name: "Settings", exact: true })).toBeHidden();
  await rail.getByRole("button", { name: "Collapse sidebar", exact: true }).click();
  expect((await rail.boundingBox())?.width).toBe(52);
  expect((await page.locator(".topbar").boundingBox())?.x).toBe(52);
  expect((await page.locator(".board-column").first().boundingBox())?.x).toBe(76);
  await expect(rail.getByRole("button", { name: "Expand sidebar", exact: true })).toBeFocused();
  await expect(rail.locator(".rail-brand-name")).toBeHidden();
  await expect(rail.getByLabel("Project", { exact: true })).toBeHidden();
  await expect(rail.getByRole("button", { name: "Settings", exact: true })).toBeVisible();
  await rail.getByRole("button", { name: "Inbox", exact: true }).click();
  await expect(page.locator(".board-panel")).toHaveAttribute("data-page", "inbox");
  await rail.getByRole("button", { name: "Tasks", exact: true }).focus();
  await page.keyboard.press("Enter");
  await expect(page.locator(".task-card")).toHaveCount(6);
  await page.reload();
  await expect(rail.getByRole("button", { name: "Expand sidebar", exact: true })).toBeVisible();
  expect((await rail.boundingBox())?.width).toBe(52);
  await page.screenshot({ path: info.outputPath("sidebar-collapsed.png") });
  await rail.getByRole("button", { name: "Settings", exact: true }).click();
  await page.getByRole("button", { name: "Appearance", exact: true }).click();
  await page.getByRole("button", { name: "Dark", exact: true }).click();
  await expect(page.locator("html")).toHaveAttribute("data-theme", "dark");
  await page.screenshot({ path: info.outputPath("sidebar-dark.png") });
  await rail.getByRole("button", { name: "Expand sidebar", exact: true }).click();
  expect((await rail.boundingBox())?.width).toBe(252);
  await expect(rail.getByLabel("Project", { exact: true })).toBeVisible();
  await expect(rail.getByRole("button", { name: "Collapse sidebar", exact: true })).toBeFocused();
  await page.reload();
  await expect(rail.getByRole("button", { name: "Collapse sidebar", exact: true })).toBeVisible();
  expect(writes).toEqual([]); expect(errors).toEqual([]);
});

test("mobile drawer closes by Escape, backdrop and navigation without losing desktop state", async ({ page }, info) => {
  const { writes, errors } = await installUiFixture(page);
  await page.goto("/?project=ui-review&page=board");
  await expect(page.locator(".task-card")).toHaveCount(6);
  await page.getByRole("button", { name: "Collapse sidebar", exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  const open = page.getByRole("button", { name: "Open navigation", exact: true });
  const drawer = page.getByRole("dialog", { name: "Navigation rail" });
  await open.click();
  await expect(drawer).toBeVisible();
  expect(await drawer.boundingBox()).toEqual({ x: 0, y: 0, width: 280, height: 844 });
  await expect(drawer.locator(".rail-brand-name")).toBeVisible();
  await expect(drawer.getByLabel("Project", { exact: true })).toBeVisible();
  await expect(page.locator(".board-panel")).toHaveJSProperty("inert", true);
  const close = drawer.getByRole("button", { name: "Close navigation", exact: true });
  await expect(close).toBeFocused();
  await page.keyboard.press("Shift+Tab");
  await expect(drawer.getByRole("button", { name: "Settings", exact: true })).toBeFocused();
  await page.keyboard.press("Tab");
  await expect(close).toBeFocused();
  await page.screenshot({ path: info.outputPath("sidebar-mobile.png") });
  await page.keyboard.press("Escape");
  await expect(drawer).toBeHidden();
  await expect(open).toBeFocused();
  await expect(page.locator(".board-panel")).toHaveJSProperty("inert", false);
  await open.click();
  await page.mouse.click(350, 200);
  await expect(drawer).toBeHidden();
  await open.click();
  await drawer.getByRole("button", { name: "Settings", exact: true }).click();
  await expect(page.getByTestId("general-settings")).toBeVisible();
  await expect(drawer).toBeHidden();
  await expect(open).toBeFocused();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390);
  await open.click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await expect(drawer).toBeHidden();
  await expect(page.locator(".topbar")).toHaveJSProperty("inert", false);
  expect((await page.locator(".project-rail").boundingBox())?.width).toBe(52);
  await expect(page.getByRole("button", { name: "Expand sidebar", exact: true })).toBeVisible();
  expect(writes).toEqual([]); expect(errors).toEqual([]);
});

test("sidebar remains usable when preference storage is blocked", async ({ page }) => {
  const { errors } = await installUiFixture(page);
  await page.addInitScript(() => {
    const original = Storage.prototype.setItem;
    Storage.prototype.setItem = function (key, value) {
      if (key === "zf.sidebarCollapsed.v1") throw new DOMException("Storage unavailable", "SecurityError");
      original.call(this, key, value);
    };
  });
  await page.goto("/?project=ui-review&page=board");
  await page.getByRole("button", { name: "Collapse sidebar", exact: true }).click();
  await expect(page.getByRole("button", { name: "Expand sidebar", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Expand sidebar", exact: true }).click();
  await expect(page.getByRole("button", { name: "Collapse sidebar", exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
