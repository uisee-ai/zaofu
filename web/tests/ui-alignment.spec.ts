  expect((await page.locator(".inbox-queue").boundingBox())?.y).toBe(46);
  await page.getByTestId("inbox-queue-item").nth(1).click();
  await expect(page.locator(".inbox-reading-pane")).toContainText("Confirm task view acceptance");
  await page.screenshot({ path: info.outputPath("inbox-desktop.png"), fullPage: true });
  expect(writes).toEqual([]);
  await page.locator(".inbox-reading-pane").getByRole("button", { name: "Preview", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "Plan preview" })).toBeVisible();
  await expect(page.getByRole("dialog", { name: "Plan preview" })).toContainText("Preserve canonical task state");
  expect(writes).toEqual([]);
  await page.getByRole("button", { name: "Close preview", exact: true }).click();
  await page.locator(".inbox-reading-pane").getByRole("button", { name: "Approve", exact: true }).click();
