import { expect, test } from "@playwright/test";

test("Inbox reads and Plan decisions reach the real backend", async ({ page, request }) => {
  test.setTimeout(45_000);
  test.skip(process.env.ZF_INBOX_BROWSER_FIXTURE !== "plan", "requires the isolated plan fixture");
  const workspace = await (await request.get("/api/workspace/projects")).json();
  const projectId = String(workspace.active_project_id);
  const api = `/api/projects/${encodeURIComponent(projectId)}/operator/inbox`;
  await page.addInitScript(() => window.localStorage.setItem("zf.webActionToken", "zf-isolated-inbox-browser"));
  await page.goto(`/?project=${encodeURIComponent(projectId)}&page=inbox`);
  const skipOnboarding = page.getByRole("button", { name: /跳过全部|Skip all/ });
  if (await skipOnboarding.isVisible()) await skipOnboarding.click();
  const plan = page.locator('[data-inbox-id="plan:plan-inbox"]');
  const question = page.locator('[data-inbox-id="channel-question:ch-inbox:main:q-inbox"]');
  const badge = page.locator("button.rail-nav-button").filter({ hasText: /Inbox|收件箱/ }).locator(".rail-nav-badge");
  await expect(plan).toBeVisible();
  await expect(question).toBeVisible();
  await expect(plan.locator(".operator-inbox-unread-dot")).toHaveCount(1);
  await expect(page.locator(".inbox-pending-count")).toHaveText("2");
  await expect(badge).toHaveText("2");
  await plan.click();
  await expect.poll(async () => (await (await request.get(api)).json()).summary.unread).toBe(1);
  await expect(plan.locator(".operator-inbox-unread-dot")).toHaveCount(0);
  await expect(badge).toHaveText("1");
  await expect(page.locator(".inbox-pending-count")).toHaveText("2");
  await page.reload();
  await expect(plan.locator(".operator-inbox-unread-dot")).toHaveCount(0);
  await expect(question.locator(".operator-inbox-unread-dot")).toHaveCount(1);
  await expect(badge).toHaveText("1");
  await page.getByRole("button", { name: "Workflows", exact: true }).click();
  await expect(badge).toHaveText("1");
  await page.getByRole("button", { name: "Inbox", exact: true }).click();
  await plan.click();
  await page.locator(".inbox-reading-pane").getByRole("button", { name: "Approve", exact: true }).click();
  await expect.poll(async () => (await (await request.get(api)).json()).summary.action_required_pending).toBe(1);
  const approvals = await (await request.get(`/api/projects/${encodeURIComponent(projectId)}/events?type=plan.approved`)).json();
  expect(approvals.items).toHaveLength(1);
  const recorded = await (await request.get(`/api/projects/${encodeURIComponent(projectId)}/events/${approvals.items[0].id}`)).json();
  expect(recorded.event.payload.request_event_id).toBe("evt-plan-inbox");
  await page.getByRole("button", { name: "Resolved", exact: true }).click();
  await plan.click();
  await expect(page.locator(".inbox-reading-pane").getByRole("button", { name: "Approve", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Needs action", exact: true }).click();
  await page.getByRole("button", { name: "Mark all read" }).click();
  await expect.poll(async () => (await (await request.get(api)).json()).summary.unread).toBe(0);
  await expect(badge).toHaveCount(0);
  const final = await (await request.get(api)).json();
  expect(final.summary.action_required_pending).toBe(1);
  expect(final.items.find((item: { id: string }) => item.id === "channel-question:ch-inbox:main:q-inbox").unread).toBe(false);
});
