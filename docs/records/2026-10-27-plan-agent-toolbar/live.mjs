import { chromium } from '/home/uisee/workspace/zaofu/web/node_modules/playwright-core/index.mjs';
import { expect as baseExpect } from '/home/uisee/workspace/zaofu/web/node_modules/@playwright/test/index.mjs';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const expect = baseExpect.configure({ timeout: 60000 });
const browser = await chromium.launch({ headless: true, executablePath: '/ms-playwright/chromium-1226/chrome-linux64/chrome' });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await page.addInitScript(token => { localStorage.setItem('zf.webActionToken', token); localStorage.setItem('zf.themeMode', 'light'); }, process.env.ZF_E2E_TOKEN);
  const project = 'ty-review-42cb2551', planId = 'evt-38c86009183e';
  const url = `http://127.0.0.1:8002/api/projects/${project}/plans/${planId}/preview`;
  const original = await (await page.request.get(url)).json();
  assert.equal(original.status, 'pending');
  let applies = 0, approvals = 0, legacyChats = 0;
  page.on('request', r => {
    if (r.method() !== 'POST') return;
    if (r.url().endsWith('/plan-artifact-review') && r.postDataJSON()?.operation === 'apply') applies++;
    if (r.url().includes('/actions/plan-approve')) approvals++;
    if (r.url().includes('/actions/chat-orchestrator')) legacyChats++;
  });
  await page.goto(`http://127.0.0.1:8002/?project=${project}&page=inbox&plan=${planId}`);
  const panel = page.getByRole('dialog', { name: 'Plan preview', exact: true });
  await panel.getByRole('button', { name: '引用编辑', exact: true }).click();
  const toolbar = panel.getByRole('navigation', { name: 'Plan document view' });
  await expect(toolbar.locator(':scope > button')).toHaveText(['Preview', 'Raw', 'Agent']);
  const documentTop = (await panel.getByTestId('plan-review-document').boundingBox()).y;
  const before = '用户打开一个静态页面即可计数', after = '用户打开计数器页面即可开始计数';
  const paragraph = panel.locator('.plan-review-block').filter({ hasText: before }).first().locator('p').first();
  await expect(paragraph).toBeVisible();
  await expect(panel.getByRole('button', { name: '引用编辑此段' })).toHaveCount(0);
  const menu = panel.getByRole('button', { name: '引用到 Agent', exact: true });
  await expect(menu).toHaveCount(0);
  await panel.screenshot({ path: '/evidence/01-clean-document.png' });
  await paragraph.scrollIntoViewIfNeeded();
  const bounds = await paragraph.boundingBox();
  await page.mouse.move(bounds.x + 2, bounds.y + 10);
  await page.mouse.down();
  await page.mouse.move(bounds.x + 235, bounds.y + 10, { steps: 15 });
  await page.mouse.up();
  await expect(menu).toBeVisible();
  assert(await page.evaluate(() => window.getSelection().toString().trim().length > 0));
  await panel.screenshot({ path: '/evidence/02-selection-action.png' });
  await menu.click();
  const agent = panel.getByRole('dialog', { name: 'Plan Agent', exact: true });
  await expect(agent.getByRole('textbox')).toBeFocused();
  await expect(agent.getByTestId('plan-review-quote')).toContainText(before);
  await expect(menu).toHaveCount(0);
  const aligned = async () => {
    const bar = await toolbar.boundingBox(), popup = await agent.boundingBox();
    assert(popup.y >= bar.y + bar.height && popup.y < bar.y + bar.height + 16);
    assert(Math.abs(popup.x - bar.x) < 1);
    assert(popup.x + popup.width <= page.viewportSize().width);
    return { toolbar: bar, agent: popup };
  };
  const desktop = await aligned();
  assert(Math.abs((await panel.getByTestId('plan-review-document').boundingBox()).y - documentTop) < 1);
  await agent.getByRole('button', { name: 'Close agent chat', exact: true }).click();
  await toolbar.getByRole('button', { name: 'Agent', exact: true }).click();
  await expect(agent.getByTestId('plan-review-quote')).toContainText(before);
  await panel.screenshot({ path: '/evidence/03-quoted-agent.png' });
  const response = page.waitForResponse(r => r.url().endsWith('/plan-artifact-review') && r.request().postDataJSON()?.operation === 'discuss', { timeout: 240000 });
  await agent.getByRole('textbox').fill(`只将引用里的“${before}”替换为“${after}”，其余所有字符和 Markdown 保持不变。只生成局部候选，不批准或启动实施。`);
  await agent.getByRole('button', { name: 'Send', exact: true }).click();
  const candidate = await (await response).json();
  assert(candidate.ok && candidate.draft_ref);
  assert.equal(candidate.after, candidate.before.replace(before, after));
  assert.equal(candidate.preview, original.markdown.replace(before, after));
  await expect(panel.getByRole('button', { name: 'Approve', exact: true })).toBeDisabled();
  await expect(agent.getByRole('button', { name: 'Apply', exact: true })).toBeEnabled();
  await fs.writeFile('/evidence/real-candidate.json', JSON.stringify(candidate, null, 2));
  await panel.screenshot({ path: '/evidence/04-real-agent-diff.png' });
  await agent.getByRole('button', { name: 'Discard', exact: true }).click();
  await expect(panel.getByRole('button', { name: 'Approve', exact: true })).toBeEnabled();
  await agent.getByRole('button', { name: 'Close agent chat', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await paragraph.scrollIntoViewIfNeeded();
  await paragraph.evaluate(element => {
    const range = document.createRange(); range.selectNodeContents(element);
    const selection = window.getSelection(); selection.removeAllRanges(); selection.addRange(range);
  });
  await expect(menu).toBeVisible();
  const menuBounds = await menu.boundingBox();
  assert(menuBounds.x >= 0 && menuBounds.x + menuBounds.width <= 390);
  await menu.click();
  await expect(agent).toBeVisible();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  const mobile = await aligned();
  const trigger = await toolbar.getByRole('button', { name: 'Agent', exact: true }).boundingBox();
  const preview = await toolbar.getByRole('button', { name: 'Preview', exact: true }).boundingBox();
  assert(Math.abs(trigger.y - preview.y) < 1);
  await panel.screenshot({ path: '/evidence/05-mobile-agent.png' });
  const current = await (await page.request.get(url)).json();
  assert.equal(current.status, 'pending'); assert.equal(current.markdown, original.markdown);
  assert.equal(applies + approvals + legacyChats, 0);
  await fs.writeFile('/evidence/result.json', JSON.stringify({ project, planId, passed: true, desktop, mobile, toolbarAgent: true, popupBelowToolbar: true, documentNotShifted: true, noPerParagraphButtons: true, nativeMouseSelection: true, contextualQuoteAction: true, realProviderLocalDiff: true, approvalLockedWithDraft: true, mobileOverflow: false, planUnchanged: true, status: current.status, applies, approvals, legacyChats }, null, 2));
  console.log('real selection -> Agent -> local Diff verified; draft discarded; Plan remains pending');
} finally { await browser.close(); }
