import { chromium } from '/home/uisee/workspace/zaofu/web/node_modules/playwright-core/index.mjs';
import { expect as baseExpect } from '/home/uisee/workspace/zaofu/web/node_modules/@playwright/test/index.mjs';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const expect = baseExpect.configure({ timeout: 60000 });
const browser = await chromium.launch({ headless: true, executablePath: '/ms-playwright/chromium-1226/chrome-linux64/chrome' });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await page.addInitScript(token => { localStorage.setItem('zf.webActionToken', token); localStorage.setItem('zf.themeMode', 'light'); }, process.env.ZF_E2E_TOKEN);
  const project = 'ty-review-42cb2551', id = 'workflow-3dc6ff5623188714';
  const api = `http://127.0.0.1:8002/api/projects/${project}/workflow-requests/${id}`;
  const original = await (await page.request.get(api)).json();
  let applies = 0, actions = 0;
  page.on('request', request => {
    if (request.method() !== 'POST') return;
    if (request.url().includes('/actions/')) actions++;
    if (request.url().endsWith('/workflow-preview-review') && request.postDataJSON()?.operation === 'apply') applies++;
  });
  await page.goto(`http://127.0.0.1:8002/?project=${project}&page=workflows&request=${id}`);
  await page.getByRole('button', { name: 'Dag', exact: true }).click();
  await page.getByRole('button', { name: 'Raw', exact: true }).click();
  const raw = page.getByRole('complementary', { name: 'Raw YAML', exact: true });
  const yaml = await raw.locator('pre').textContent();
  await raw.getByRole('button', { name: 'Agent', exact: true }).click();
  const agent = page.getByRole('dialog', { name: 'Workflow Agent', exact: true });
  await expect(agent.getByRole('textbox')).toBeEnabled();
  await expect(agent.getByTestId('workflow-agent-availability')).toContainText('可以提问讨论');
  await agent.getByRole('textbox').fill('请只根据当前冻结 YAML 简短说明 impl 与 verify 的 lanes，并引用对应字段。不要修改配置或启动任何工作。');
  await expect(agent.getByRole('button', { name: 'Send', exact: true })).toBeEnabled();
  await agent.screenshot({ path: '/evidence/01-input-enabled.png' });
  const response = page.waitForResponse(r => r.url().endsWith('/workflow-preview-review') && r.request().postDataJSON()?.operation === 'discuss', { timeout: 240000 });
  await agent.getByRole('button', { name: 'Send', exact: true }).click();
  const result = await (await response).json();
  assert(result.ok, JSON.stringify(result)); assert(result.answer.trim());
  assert.deepEqual(result.changes, []); assert.equal(result.draft_ref, null);
  await expect(agent.getByTestId('review-answer')).toContainText(result.answer);
  await expect(agent.getByRole('button', { name: 'Apply', exact: true })).toHaveCount(0);
  await page.screenshot({ path: '/evidence/02-real-answer.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(agent.getByRole('textbox')).toBeEnabled();
  await agent.getByRole('textbox').fill('继续讨论');
  await expect(agent.getByRole('button', { name: 'Send', exact: true })).toBeEnabled();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await agent.screenshot({ path: '/evidence/03-mobile.png' });
  await expect(raw.locator('pre')).toHaveText(yaml);
  const current = await (await page.request.get(api)).json();
  for (const key of ['request_id', 'revision', 'proposal_digest', 'run_id']) assert.deepEqual(current.result[key], original.result[key]);
  assert.deepEqual(current.proposal.effective_config_ref, original.proposal.effective_config_ref);
  assert.equal(actions + applies, 0);
  await fs.writeFile('/evidence/result.json', JSON.stringify({ passed: true, project, requestId: id, realProvider: true, inputEnabled: true, mobileInputEnabled: true, answer: result.answer, changes: result.changes, draft_ref: result.draft_ref, snapshotUnchanged: true, actions, applies }, null, 2));
  console.log('Running DAG Raw Agent: typed and sent; real provider replied; snapshot unchanged; no Apply or workflow action.');
} finally { await browser.close(); }
