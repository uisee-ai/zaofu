import {chromium} from '/home/uisee/workspace/zaofu/web/node_modules/playwright-core/index.mjs';
import {writeFile} from 'node:fs/promises';
const browser=await chromium.launch({headless:true,executablePath:'/ms-playwright/chromium-1226/chrome-linux64/chrome'});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
page.setDefaultTimeout(20000);
await page.addInitScript(()=>{localStorage.setItem('zf.webActionToken','raw-chat-real-fixture-token');localStorage.setItem('zf.themeMode','light');});
await page.goto('http://127.0.0.1:8003/?project=default&page=workflows&request=raw-real-review');
await page.getByRole('button',{name:'Raw',exact:true}).click();
const raw=page.getByRole('complementary',{name:'Raw YAML',exact:true});
await raw.getByRole('button',{name:'Edit with Agent',exact:true}).click();
const chat=raw.getByTestId('workflow-preview-review');
await chat.getByLabel('Review field').selectOption('config.0.lanes');
await chat.getByLabel('Preview discussion').fill('将并行任务数 lanes 从 1 修改为 2，其他配置保持不变。请返回当前字段的新整数值，不执行工具，不启动 Workflow。');
const response=page.waitForResponse(r=>r.url().endsWith('/workflow-preview-review')&&r.request().postDataJSON()?.operation==='discuss',{timeout:150000});
await chat.getByRole('button',{name:'提出局部修改',exact:true}).click();
const reply=await (await response).json();
console.log(JSON.stringify({phase:'real-provider',ok:reply.ok,status:reply.status,reason:reply.reason,answer:reply.answer,changes:reply.changes}));
await writeFile('/evidence/provider-response.json',JSON.stringify(reply,null,2));
if(!reply.ok||!reply.draft_ref) throw new Error(JSON.stringify(reply));
await chat.getByTestId('review-diff').waitFor();
await raw.screenshot({path:'/evidence/real-diff.png'});
await chat.getByRole('button',{name:'应用修改并生成新版 Preview',exact:true}).click();
await raw.locator('.workflow-raw-yaml pre').filter({hasText:'lanes: 2'}).waitFor();
await page.reload();
await page.getByRole('button',{name:'Raw',exact:true}).click();
await raw.locator('.workflow-raw-yaml pre').filter({hasText:'lanes: 2'}).waitFor();
const detail=await (await page.request.get('http://127.0.0.1:8003/api/projects/default/workflow-requests/raw-real-review')).json();
if(detail.lifecycle.submitted||detail.result.status!=='ready'||detail.proposal.approval_status!=='blocked') throw new Error('Blocked candidate was admitted');
await raw.getByRole('button',{name:'Edit with Agent',exact:true}).waitFor();
console.log(JSON.stringify({phase:'applied-and-reloaded',revision:detail.result.revision,status:detail.result.status,approval:detail.proposal.approval_status,submitted:detail.lifecycle.submitted,yamlUpdated:detail.artifacts.effective_config.yaml.includes('lanes: 2')}));
await raw.screenshot({path:'/evidence/real-yaml-after.png'});
await writeFile('/evidence/result.json',JSON.stringify({revision:detail.result.revision,status:detail.result.status,proposal:detail.proposal.proposal_digest,submitted:detail.lifecycle.submitted,yaml:detail.artifacts.effective_config.yaml},null,2));
await browser.close();
